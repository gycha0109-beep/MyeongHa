import {
  constants, existsSync, lstatSync, openSync, closeSync,
  readFileSync, fstatSync,
} from 'node:fs';
import {
  createHmac, createPublicKey, verify as verifySignature,
} from 'node:crypto';
import { isAbsolute, join, resolve } from 'node:path';

import type {
  OfficialReaderPrivatePrivacyLedgerPortV1,
  OfficialReaderPrivacyReadLeaseV1,
} from './official-reader-private-privacy-ledger-v1.js';

/**
 * S6 off-primary recovery gate.
 *
 * Paid reread requires BOTH the current PostgreSQL Entitlement and a fresh
 * independently signed, off-primary Privacy recovery acceptance. No signed
 * certificate is installed or generated by this module; missing, expired,
 * mismatched or stale evidence returns NO lease. The recovery signer MUST
 * only issue a certificate after account+refund deletion replay, restore
 * epoch reconciliation and key tombstone checks have all passed.
 *
 * The signing private key is never sent to the Reader service. The public
 * key and expected restore epoch are Owner-provisioned server settings.
 * This is not mounted on the public paid-read HTTP route until S3/S4/S8
 * acceptance and source/recovery evidence exist.
 */

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/iu;
const CERTIFICATE_FILENAME = 'reader-privacy-recovery-acceptance-v1.json';
const MAX_CERTIFICATE_BYTES = 16_384;
const MAX_LEASE_MS = 3_000;

export interface OfficialReaderRecoveryAcceptanceCertificateV1 {
  readonly version: 'official-reader-privacy-recovery-acceptance-v1';
  readonly restoreEpoch: string;
  readonly ledgerCheckpoint: string;
  readonly reconciliationDigest: string;
  readonly issuedAtEpochMs: number;
  readonly validUntilEpochMs: number;
  readonly signatureBase64Url: string;
}

export interface OfficialReaderNodeOffPrimaryPrivacyReadConfigV1 {
  readonly ledgerRoot: string;
  readonly ledgerSealKey: Uint8Array;
  readonly recoverySignerPublicKeyPem: string;
  /** Pinned from trusted server recovery configuration, never HTTP input. */
  readonly expectedRestoreEpoch: string;
}

function unavailable(): never {
  throw new Error('Protected Reader independent Privacy recovery authority is unavailable.');
}

function safeRoot(dir: string): string {
  if (typeof dir !== 'string' || !isAbsolute(dir)
      || resolve(dir) !== dir || dir === '/'
      || dir.startsWith('/tmp/') || dir.startsWith('/var/tmp/')
      || dir.startsWith('/run/')) return unavailable();
  const stat = lstatSync(dir);
  if (!stat.isDirectory() || stat.isSymbolicLink()
      || (stat.mode & 0o077) !== 0) return unavailable();
  return dir;
}

function safeReadCertificate(dir: string): unknown {
  let handle: number | undefined;
  try {
    handle = openSync(
      join(dir, CERTIFICATE_FILENAME),
      constants.O_RDONLY | constants.O_NOFOLLOW,
    );
    const stat = fstatSync(handle);
    if (!stat.isFile() || stat.size===0 || stat.size>MAX_CERTIFICATE_BYTES
        || (stat.mode & 0o077)!==0) return null;
    return JSON.parse(readFileSync(handle, { encoding: 'utf8' }));
  } catch {
    return null;
  } finally {
    if (handle !== undefined) closeSync(handle);
  }
}

export function officialReaderRecoveryAcceptanceSignaturePayloadV1(input: Readonly<{
  restoreEpoch: string;
  ledgerCheckpoint: string;
  reconciliationDigest: string;
  issuedAtEpochMs: number;
  validUntilEpochMs: number;
}>): Buffer {
  return Buffer.from(JSON.stringify([
    'official-reader-privacy-recovery-acceptance-v1',
    input.restoreEpoch, input.ledgerCheckpoint, input.reconciliationDigest,
    input.issuedAtEpochMs, input.validUntilEpochMs,
  ]), 'utf8');
}

function acceptedCertificate(
  input: unknown,
  expectedEpoch: string,
  publicKey: ReturnType<typeof createPublicKey>,
  at: number,
): OfficialReaderRecoveryAcceptanceCertificateV1 | null {
  if (!input || typeof input !== 'object' || Array.isArray(input)) return null;
  const cert = input as Record<string, unknown>;
  if (cert.version !== 'official-reader-privacy-recovery-acceptance-v1'
      || cert.restoreEpoch !== expectedEpoch
      || typeof cert.ledgerCheckpoint !== 'string'
      || cert.ledgerCheckpoint.length < 16 || cert.ledgerCheckpoint.length > 256
      || typeof cert.reconciliationDigest !== 'string'
      || !/^sha256:[a-f0-9]{64}$/u.test(cert.reconciliationDigest)
      || typeof cert.issuedAtEpochMs !== 'number'
      || typeof cert.validUntilEpochMs !== 'number'
      || !Number.isSafeInteger(cert.issuedAtEpochMs)
      || !Number.isSafeInteger(cert.validUntilEpochMs)
      || cert.issuedAtEpochMs > at
      || cert.validUntilEpochMs <= at
      || cert.validUntilEpochMs - cert.issuedAtEpochMs > 24 * 60 * 60 * 1000
      || typeof cert.signatureBase64Url !== 'string'
      || !/^[A-Za-z0-9_-]{80,120}$/u.test(cert.signatureBase64Url)) return null;

  try {
    const signature = Buffer.from(cert.signatureBase64Url, 'base64url');
    if (signature.length !== 64) return null;
    const authentic = verifySignature(
      null,
      officialReaderRecoveryAcceptanceSignaturePayloadV1({
        restoreEpoch: cert.restoreEpoch as string,
        ledgerCheckpoint: cert.ledgerCheckpoint,
        reconciliationDigest: cert.reconciliationDigest,
        issuedAtEpochMs: cert.issuedAtEpochMs,
        validUntilEpochMs: cert.validUntilEpochMs,
      }),
      publicKey,
      signature,
    );
    if (!authentic) return null;
  } catch {
    return null;
  }
  return cert as unknown as OfficialReaderRecoveryAcceptanceCertificateV1;
}

/**
 * No database access, no third-party API. Reads only a dedicated mount and
 * verifies the Recovery Owner's Ed25519 signature before any active lease.
 * Every Subject tombstone is checked again synchronously during S1 SQL
 * locking and right before plaintext can leave the private Reader service.
 */
export function createOfficialReaderNodeOffPrimaryPrivacyReadPortV1(
  config: OfficialReaderNodeOffPrimaryPrivacyReadConfigV1,
): OfficialReaderPrivatePrivacyLedgerPortV1 {
  const root = safeRoot(config.ledgerRoot);
  if (!(config.ledgerSealKey instanceof Uint8Array)
      || config.ledgerSealKey.byteLength !== 32
      || !UUID.test(config.expectedRestoreEpoch)
      || !config.recoverySignerPublicKeyPem) return unavailable();
  const seal = Buffer.from(config.ledgerSealKey);
  const publicKey = createPublicKey(config.recoverySignerPublicKeyPem);
  if (publicKey.asymmetricKeyType !== 'ed25519') return unavailable();
  const expectedEpoch = config.expectedRestoreEpoch.toLowerCase();

  function tombstoned(subjectId: string): boolean {
    if (!UUID.test(subjectId)) return true;
    const digest = createHmac('sha256', seal)
      .update(['account-subject-deny', subjectId].join('|'), 'utf8')
      .digest('hex');
    return existsSync(join(root, 'account-subject-deny-' + digest + '.json'));
  }

  function currentCertificate(at: number) {
    try {
      safeRoot(root);
      return acceptedCertificate(
        safeReadCertificate(root), expectedEpoch, publicKey, at,
      );
    } catch {
      return null;
    }
  }

  const acquireReadLease: OfficialReaderPrivatePrivacyLedgerPortV1['acquireReadLease'] =
    async (input): Promise<OfficialReaderPrivacyReadLeaseV1 | null> => {
      const subjectId = input.subjectId;
      const selector = input.selector;
      if (!UUID.test(subjectId) || typeof selector !== 'string'
          || selector.length === 0 || selector.length > 256
          || tombstoned(subjectId)) return null;
      const now = Date.now();
      const cert = currentCertificate(now);
      if (cert === null || tombstoned(subjectId)) return null;
      return Object.freeze({
        contractVersion: 'official-reader-privacy-read-lease-v1',
        subjectId, selector,
        ledgerCheckpoint: cert.ledgerCheckpoint,
        restoreEpoch: cert.restoreEpoch,
        expiresAtEpochMs: Math.min(now + MAX_LEASE_MS, cert.validUntilEpochMs),
      });
    };

  const isLeaseCurrent: OfficialReaderPrivatePrivacyLedgerPortV1['isLeaseCurrent'] =
    ({ lease, subjectId, selector, currentEpochMs }): boolean => {
      if (!lease || lease.subjectId !== subjectId || lease.selector !== selector
          || lease.restoreEpoch !== expectedEpoch
          || !Number.isSafeInteger(currentEpochMs)
          || currentEpochMs >= lease.expiresAtEpochMs
          || tombstoned(subjectId)) return false;
      const cert = currentCertificate(currentEpochMs);
      return cert !== null
        && cert.ledgerCheckpoint === lease.ledgerCheckpoint
        && cert.restoreEpoch === lease.restoreEpoch
        && !tombstoned(subjectId);
    };

  return Object.freeze({ acquireReadLease, isLeaseCurrent });
}
