/** Draw uniformly across the pool, excluding the immediately previous message. */
export function pickFortuneCookieIndexV1(previous: number, random: () => number = Math.random): number {
  const count = FORTUNE_COOKIE_MESSAGES_V1.length;
  if (count === 0) return -1;
  const validPrevious = Number.isInteger(previous) && previous >= 0 && previous < count;
  if (count === 1) return 0;
  const limit = validPrevious ? count - 1 : count;
  const draw = Math.floor(Math.max(0, Math.min(0.9999999999999999, random())) * limit);
  return validPrevious && draw >= previous ? draw + 1 : draw;
}
