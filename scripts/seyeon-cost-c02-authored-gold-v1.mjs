function groupEntries(cohort) {
  const size=cohort.texts.length;
  if(size!==10 && size!==20) throw new Error('Gold group size changed: '+cohort.key);
  return cohort.texts.map((text,index)=>{
    if(typeof text!=='string' || text.trim()!==text || text.length<5 || text.length>240) {
      throw new Error('Invalid gold input: '+cohort.key);
    }
    return Object.freeze({
      id:'C02_'+cohort.key+'_'+String(index+1).padStart(2,'0'),
      text,topic:cohort.topic,
      ...(cohort.requiredKind?{requiredKind:cohort.requiredKind}:{}),
      ...(cohort.noClaims?{noClaims:true}:{}),
    });
  });
}
